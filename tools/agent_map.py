#!/usr/bin/env python3
"""Generate .agent/CODEMAP.md - a live function/landmark index of the repo.

This is the agent pipeline's fast-lookup layer: instead of exploratory
greps across 3500-line sources, one generated file lists every function,
section banner, and key global with its exact line number.

Usage:
    python3 tools/agent_map.py           # regenerate .agent/CODEMAP.md
    python3 tools/agent_map.py --check   # fail if the committed map is stale

`--check` runs in the repository consistency suite so the map can never
quietly fall behind the code.
"""
import re
import sys
from pathlib import Path

ROOT = Path(__file__).resolve().parent.parent
OUT = ROOT / ".agent" / "CODEMAP.md"

C_FILES = [
    "project-hub/src/project_hub.c",
    "bluetooth-guard/src/bluetooth_guard.c",
    "keyboard-lighting/src/keyboard_lighting.c",
    "dns-pilot/src/dns_pilot.c",
    "agent-notes/src/agent_notes.c",
]

PY_GLOBS = ["tools/*.py", "tests/*.py"]

C_KEYWORDS = {
    "if", "for", "while", "switch", "return", "sizeof", "else", "do",
    "typedef", "struct", "enum", "union", "static", "extern", "case",
}

FUNC_RE = re.compile(r"^(?:static\s+)?(?:const\s+)?[\w\*]+\s+\**(\w+)\s*\(")
SECTION_RE = re.compile(r"/\*[\s=-]*(?:----+|====+|=+)\s*(.+?)\s*(?:----+|====+|=+)[\s=-]*\*/")
GLOBAL_RE = re.compile(r"^static\s+[^;=]*?\b(g_\w+)\s*(?:\[|=|;|\s*,)")


def comment_purpose(lines, i):
    """First sentence of the contiguous comment block above line i, if any."""
    j = i - 1
    while j >= 0 and not lines[j].strip():
        j -= 1
    if j < 0:
        return ""
    block = []
    while j >= 0:
        s = lines[j].strip()
        if s.startswith("/*") or s.startswith("*") or s.startswith("//"):
            s = s.lstrip("/*").lstrip("/").strip().rstrip("*/").strip()
            if s:
                block.append(s)
            j -= 1
        else:
            break
    if not block:
        return ""
    text = block[-1]  # topmost line of the block = its first sentence
    text = re.split(r"(?<=[.!?])\s", text)[0]
    return text[:100]


def scan_c(path):
    lines = (ROOT / path).read_text(encoding="utf-8", errors="replace").splitlines()
    out = []          # (lineno, kind, name, purpose)
    globals_ = []
    in_block = False
    for i, line in enumerate(lines):
        s = line.strip()
        m = SECTION_RE.search(line)
        if m:
            out.append((i + 1, "S", m.group(1), ""))
        if "/*" in line and "*/" not in line:
            in_block = True
        if "*/" in line:
            in_block = False
        if not in_block and line and not line.startswith((" ", "\t", "#", "/", "*")):
            if "(" in line and not s.endswith(";") and "=" not in line.split("(")[0]:
                m = FUNC_RE.match(line)
                if m and m.group(1) not in C_KEYWORDS:
                    out.append((i + 1, "F", m.group(1), comment_purpose(lines, i)))
        m = GLOBAL_RE.match(line)
        if m:
            globals_.append((i + 1, m.group(1)))
    return out, globals_


def scan_py(path):
    lines = (ROOT / path).read_text(encoding="utf-8", errors="replace").splitlines()
    out = []
    re_def = re.compile(r"^(?:def|class)\s+(\w+)")
    for i, line in enumerate(lines):
        m = re_def.match(line)
        if m:
            out.append((i + 1, "F", m.group(1), ""))
    return out, []


def build():
    parts = [
        "# Code Map",
        "",
        "> Generated by `python3 tools/agent_map.py` - do not edit by hand.",
        "> `python3 tools/agent_map.py --check` (run in check_all) fails when stale.",
        "> Read this instead of grepping blind: every entry is `L<line>  name`.",
        "",
    ]
    for path in C_FILES + [p for pat in PY_GLOBS for p in sorted(
            str(q.relative_to(ROOT)) for q in ROOT.glob(pat))]:
        entries, globals_ = (scan_c(path) if path.endswith(".c") else scan_py(path))
        parts.append(f"## {path}")
        parts.append("")
        for lineno, kind, name, purpose in entries:
            tag = "S" if kind == "S" else "f"
            note = f"  — {purpose}" if purpose else ""
            parts.append(f"- L{lineno}  {tag} {name}{note}")
        if globals_:
            joined = ", ".join(f"{name} (L{lineno})" for lineno, name in globals_)
            parts.append(f"- globals: {joined}")
        parts.append("")
    return "\n".join(parts) + "\n"


def main():
    text = build()
    if "--check" in sys.argv:
        if not OUT.exists() or OUT.read_text(encoding="utf-8") != text:
            print("stale .agent/CODEMAP.md - run: python3 tools/agent_map.py")
            return 1
        return 0
    OUT.write_text(text, encoding="utf-8")
    print(f"wrote {OUT.relative_to(ROOT)} ({len(text.splitlines())} lines)")
    return 0


if __name__ == "__main__":
    sys.exit(main())
