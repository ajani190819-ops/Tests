"""Preview-visible geometry-stage Wave Overhangs prototype.

This is intentionally a separate plugin from Wave Overhangs. The stable plugin
waits for exported Bridge G-code and is still the fallback. This prototype now
runs at ``posPrepareInfill`` and edits Orca's prepared infill surfaces instead:

* Orca keeps the original slice and generates the normal perimeter first;
* the previous layer supplies the support footprint;
* unsupported fill surfaces are replaced with fixed-spacing Wave ribbons;
* the ribbons are written back into ``LayerRegion.fill_surfaces`` as bridges;
* Orca's normal infill stage turns those bridge surfaces into preview roles.

The current Python host API does not provide a writable ExtrusionPath collection.
Therefore this plugin cannot inject a raw Wave polyline directly into Orca's
extrusion graph. It creates preview-visible Wave ribbon fill surfaces, which
Orca then turns into ordinary bridge toolpaths. That distinction is reported by
Check setup and is kept visible in the documentation; it must not be described
as a direct ExtrusionPath injector until Orca exposes that mutator.

Every geometry edit is contained in the execute call. Invalid or incomplete
host bindings leave the slice unchanged and return a recoverable result.
"""
from __future__ import annotations

import json
import math
import os
import time

try:
    # Import at module load so Orca's audit hook cannot block a lazy import
    # during execute(). Orca installs these dependencies for the plugin; the
    # fallback keeps Diagnostics and the audit test usable if they are absent.
    import numpy as np
    import shapely
    from shapely.geometry import GeometryCollection, LineString, MultiPolygon, Polygon
    from shapely.ops import linemerge, unary_union
    _DEPS_ERROR = None
except ImportError as exc:  # pragma: no cover - exercised without Orca deps
    np = None
    shapely = None
    GeometryCollection = LineString = MultiPolygon = Polygon = None
    linemerge = unary_union = None
    _DEPS_ERROR = f"Wave Overhangs Geometry needs numpy and shapely: {exc}"

